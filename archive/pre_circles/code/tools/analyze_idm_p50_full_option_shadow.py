"""Measure p50 command distinctness along an unchanged p30 treatment trace."""

from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Any, Iterable

import numpy as np

from experiments.io import atomic_write_json


SCHEMA = "idm_p50_full_option_shadow/1"


def analyze(
    inputs: Iterable[Path], distinct_threshold_mps2: float = 0.05
) -> dict[str, Any]:
    rows: list[dict[str, Any]] = []
    case_ids: set[str] = set()
    command_counts: dict[str, int] = {}
    for root in sorted(set(path.resolve() for path in inputs)):
        branches = root / "branches" if root.is_dir() else root.parent
        files = sorted(branches.glob("*.json")) if branches.is_dir() else [root]
        for path in files:
            try:
                branch = json.loads(path.read_text(encoding="utf-8"))
            except (OSError, json.JSONDecodeError):
                continue
            if branch.get("is_control") or branch.get("mode") != "speed_ceiling":
                continue
            case_id = str(branch.get("case_id", path.stem))
            case_ids.add(case_id)
            command_counts[case_id] = len(branch.get("command_rows", []))
            for command in branch.get("command_rows", []):
                shadow = command.get("p50_shadow")
                actual = command.get("projected_acceleration_mps2")
                desired = command.get("desired_acceleration_mps2")
                if not isinstance(shadow, dict) or actual is None or desired is None:
                    continue
                rows.append(
                    {
                        "case_id": case_id,
                        "seed": branch.get("seed"),
                        "relative_step": int(command["relative_step"]),
                        "actual_p30_desired_mps2": float(desired),
                        "shadow_p50_desired_mps2": float(
                            shadow["desired_acceleration_mps2"]
                        ),
                        "actual_p30_projected_mps2": float(actual),
                        "shadow_p50_projected_mps2": float(
                            shadow["projected_acceleration_mps2"]
                        ),
                        "desired_delta_mps2": float(
                            shadow["desired_acceleration_mps2"]
                        )
                        - float(desired),
                        "projected_delta_mps2": float(
                            shadow["projected_acceleration_mps2"]
                        )
                        - float(actual),
                    }
                )
    threshold = float(distinct_threshold_mps2)

    def metrics(
        selected: list[dict[str, Any]], total_command_count: int
    ) -> dict[str, Any]:
        desired = np.asarray(
            [abs(row["desired_delta_mps2"]) for row in selected], dtype=float
        )
        projected = np.asarray(
            [abs(row["projected_delta_mps2"]) for row in selected], dtype=float
        )
        return {
            "command_count": len(selected),
            "total_p30_command_count": int(total_command_count),
            "shadow_coverage_fraction": (
                len(selected) / total_command_count if total_command_count else None
            ),
            "desired_median_absolute_delta_mps2": (
                float(np.median(desired)) if desired.size else None
            ),
            "desired_distinct_fraction": (
                float(np.mean(desired >= threshold)) if desired.size else None
            ),
            "projected_median_absolute_delta_mps2": (
                float(np.median(projected)) if projected.size else None
            ),
            "projected_distinct_fraction": (
                float(np.mean(projected >= threshold)) if projected.size else None
            ),
        }

    by_case: dict[str, dict[str, Any]] = {}
    for case_id in sorted(case_ids):
        selected = [row for row in rows if row["case_id"] == case_id]
        by_case[case_id] = metrics(selected, command_counts.get(case_id, 0))
    total_commands = sum(command_counts.values())
    return {
        "schema": SCHEMA,
        "diagnostic_only": True,
        "scientific_claim": (
            "The shadow uses states generated by p30 and does not estimate p50 "
            "treatment outcomes or authorize p50 execution."
        ),
        "distinct_threshold_mps2": threshold,
        "case_count": len(case_ids),
        "all_commands": metrics(rows, total_commands),
        "after_first_step": metrics(
            [row for row in rows if row["relative_step"] > 1],
            max(total_commands - len(case_ids), 0),
        ),
        "case_projected_distinct_fraction_at_least_30pct": (
            float(
                np.mean(
                    [
                        value["projected_distinct_fraction"] >= 0.30
                        for value in by_case.values()
                        if value["projected_distinct_fraction"] is not None
                    ]
                )
            )
            if by_case
            else None
        ),
        "by_case": by_case,
        "rows": rows,
    }


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--inputs", nargs="+", required=True, type=Path)
    parser.add_argument("--output", required=True, type=Path)
    parser.add_argument("--distinct-threshold-mps2", type=float, default=0.05)
    args = parser.parse_args()
    result = analyze(args.inputs, args.distinct_threshold_mps2)
    output = args.output
    if output.suffix.lower() != ".json":
        output = output / "summary.json"
    atomic_write_json(output, result)
    print(json.dumps({key: value for key, value in result.items() if key != "rows"}, indent=2))


if __name__ == "__main__":
    main()
