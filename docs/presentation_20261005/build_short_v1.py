"""3-slide deck. python build_short.py -> WM_short_20261005.pptx + OUTLINE_short.md (reuses build_deck helpers)."""
import os, sys
HERE = os.path.dirname(os.path.abspath(__file__)); sys.path.insert(0, HERE)
import build_deck as bd
from pptx.enum.text import MSO_ANCHOR

bd.FOOT = "WM-N1 world model | 2026-10-05 | seconds; lower is better for errors and delay"
prs = bd.prs; S = bd.new_slide
tb, table, takeaway = bd.tb, bd.table, bd.takeaway

# 1
s = S("WM-N1 world model — progress (2026-10-05)", "Title page.", ["Title", "Subtitle"])
tb(s, 0.5, 2.6, 12.3, 1.2, "What the model achieves now, and what we fix next", size=34, color="0E7C86", bold=True)
tb(s, 0.5, 6.0, 12.3, 0.6, "Jinghan Peng | 2026-10-05", size=18)

# 2
s = S("What our world model achieves now",
      "Prediction vs reality for the PI-vs-native delay effect on 30 fresh worlds (post-hoc, source scorer-repl ACCURACY.md). Values A13 (A11). Direction accuracy among pairs with |true| >= 1 s; coverage of the model 80% range, ideal 80%; Spearman rank correlation. Callouts: open-road imagination fix cut error 3564 s to 947 s (real-future best case 761 s; source rollout-entry ENTRY_FIX.md). Decisions on 30 fresh worlds tie always-native (regret 1073 vs 1117 s, A11). Controllers do help: always-PI -1221 s total delay over 10 min; best-per-situation headroom about 1100 s per decision at 300 s. Takeaway: the model knows whether PI helps with honest uncertainty, not yet how much.",
      ["Table 30 s / 300 s", "3 callouts", "Takeaway"])
tb(s, 0.4, 1.35, 7.6, 0.5, "Prediction vs reality: PI effect, 30 fresh worlds", size=20, color="1F3A5F", bold=True)
rows = [["Horizon", "Error A13 (A11), s", "True effect size, s", "Direction right", "80%-range coverage", "Rank corr."],
        ["30 s", "16.1 (21.0)", "18.3", "85% (81%)", "87% (63%)", "0.45 (0.29)"],
        ["300 s", "963 (957)", "1057", "77% (73%)", "83% (80%)", "0.44 (0.26)"]]
table(s, 0.4, 1.9, 7.6, rows, col_w=[1.0, 1.5, 1.3, 1.25, 1.35, 1.2], size=15, row_h=0.95)
tb(s, 0.4, 5.0, 7.6, 1.0, "Coverage ideal: 80%. Numbers in brackets: A11.", size=16, color="666666")
boxes = ["Open-road imagination fix: prediction error 3564 s → 947 s (best case with real future: 761 s)",
         "Decisions on 30 fresh worlds: ties always-native (regret 1073 vs 1117 s)",
         "Controllers do help: always-PI −1221 s total delay (10 min); best-per-situation headroom ~1100 s per decision"]
for i, t in enumerate(boxes):
    tb(s, 8.3, 1.4 + i * 1.6, 4.6, 1.45, t, size=17, color="1F3A5F", bold=True, fill="EEF3F7", line="0E7C86", anchor=MSO_ANCHOR.MIDDLE, name="callout")
takeaway(s, "Knows whether PI helps (77-85%) with honest uncertainty; not yet how much → decisions tie native", y=6.1, h=0.8)

# 3
s = S("Next: fixes, in order", "Six planned fixes, each with what it addresses. Goal: turn knowing the direction into knowing the size.", ["6 numbered fixes", "goal bar"])
rows = [["#", "Fix", "What it addresses"],
        ["1", "Realistic queues & speeds in the imagined future", "Plans look alike (rollout 22-27 vs 16-23 m/s, no queues)"],
        ["2", "Per-CAV plan input (A14)", "Model can't see which CAV does what, or where"],
        ["3", "Physics-measured short-horizon delay + learned long-horizon (blend)", "Use simulated driver reactions directly"],
        ["4", "Keep 300 s sharpness with A13's 30 s fix", "A13 traded some 300 s accuracy"],
        ["5", "Tests: unseen controller (leave-PI-out), seed variance", "Generalisation + reliability"],
        ["6", "Re-test decisions on fresh worlds + closed loop", "The real goal: beat always-native"]]
table(s, 0.4, 1.4, 12.5, rows, col_w=[0.6, 6.2, 5.7], size=19, row_h=0.64)
takeaway(s, "Goal: turn ‘knows the direction’ into ‘knows the size’ → capture the ~1100 s/decision headroom", y=6.2, h=0.75)

prs.save(os.path.join(HERE, "WM_short_20261005.pptx"))
out = ["# WM-N1 short deck - outline and speaker notes (generated by build_short.py)\n"]
for n, t, ls, nt in bd.OUTLINE:
    out.append(f"## Slide {n}: {t}\n"); out += [f"- {l}" for l in ls]; out.append(f"\n**Notes:** {nt}\n")
open(os.path.join(HERE, "OUTLINE_short.md"), "w", encoding="utf-8").write("\n".join(out))
print(len(prs.slides), "slides"); print("\n".join(bd.WARN) or "no overflow warnings")
