"""WD-01-PA2G-LC2 report generator: REPORT_PA2G_LC2.md from lc2_summary
.json + lc2_run_meta.json (aggregation only; every number machine-sourced).
"""
from __future__ import annotations

import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
RESULTS = HERE / "results" / "lc2"
OUT = HERE / "REPORT_PA2G_LC2.md"
HS = (10, 30, 60, 120)
VARIANTS = ("va", "vb", "vc", "vabc")

VARIANT_SPECS = {
    "va": ("V-a persistence",
           "A discretionary change fires only if the MOBIL criterion "
           "(incentive + safety) has held continuously for "
           "T_persist = 2.0 s (4 steps at dt 0.5). Implementation: a "
           "per-(vehicle, target-lane) consecutive-qualifying-step "
           "counter in the engine's discretionary loop; any failing "
           "step resets it; firing resets the vehicle's counters. "
           "Anti-flicker / decision-persistence device; value = 4 "
           "integration steps, chosen a priori, NOT fitted."),
    "vb": ("V-b manoeuvre time",
           "After ANY lane change the same vehicle may not start "
           "another DISCRETIONARY change for T_lc = 4.0 s (the change "
           "itself stays instantaneous; mandatory merges are NOT "
           "gated). Implementation: the discretionary candidacy gate "
           "uses max(nominal cooldown, T_lc) on the last-change time; "
           "merge candidacy keeps the nominal cooldown only. "
           "Provenance: empirical lane-change durations are reported "
           "at around 4-5 s (Toledo & Zohar 2007 - exact citation TO "
           "VERIFY per the registration's flag); value chosen a "
           "priori, NOT fitted."),
    "vc": ("V-c strategic early merge",
           "An accel-lane vehicle applies the mandatory-merge rule "
           "from the START of the merge zone (candidacy window "
           "already spans [zone_s0_m, zone_s1_m] = [378.66, 454.10], "
           "unchanged) with ZERO incentive threshold, plus a merge "
           "bias b_merge = 1.0 m/s^2 added to its MOBIL gain toward "
           "main_right. The safe-gap tests (lead headway, follower "
           "s0, b_safe(u) both sides) are UNCHANGED (test-pinned). "
           "Provenance: on-ramp bias convention of Treiber/Kesting-"
           "style MOBIL implementations; value chosen a priori, NOT "
           "fitted."),
}


def fmt(x, nd=3):
    if x is None:
        return "-"
    if isinstance(x, float):
        return f"{x:.{nd}f}"
    return str(x)


def main():
    s = json.loads((RESULTS / "lc2_summary.json").read_text(
        encoding="utf-8"))
    meta = json.loads((RESULTS / "lc2_run_meta.json").read_text(
        encoding="utf-8"))
    tab, cis, dec = s["table"], s["cis"], s["decisions"]
    L = []
    w = L.append
    w("# REPORT - WD-01-PA2G-LC2: structural lane-change sensitivity "
      "of Part A v2 general")
    w("")
    w("- **Registration:** `output/wd01/REGISTRATION_PA2G_LC2.md` "
      "(LF-sha256 prefix 725e0a876c554d7b, verified before execution).")
    w("- **Type:** descriptive SENSITIVITY ANALYSIS, TRAIN only, zero "
      "SUMO. Every variant is OFF by default; values are the "
      "registered a-priori ones (`partA_v2g/variants_lc2.json`, never "
      "tuned/swept/selected). Nothing feeds back into the nominal "
      "model.")
    w(f"- **Panel:** the same 32 PA2G-A2 TRAIN worlds of chunk 4 "
      f"(`results/lc1_a2_worlds32.json`), 18 windows each "
      f"(w = t0+30k, k=1..18), H in {{10, 30, 60, 120}}, post-LC1 "
      f"counting convention. {meta['raw_rows']} raw eval rows + "
      f"{meta['merge_rows']} raw merge-outcome rows saved BEFORE "
      f"aggregation (`results/lc2/lc2_rows.jsonl`, "
      f"`lc2_merge_outcomes.jsonl`).")
    w("- **params_nominal.json UNCHANGED:** param_set_id "
      "`BA1FD93F0A21B1FFD2CDF20693E74FB8E3FBB8E4A1C57E7F88D9A3929E345"
      "5CE` verified before and after; the variant flags live in a "
      "separate injected `lc_variants` section (engine + "
      "`variants_lc2.json`), absent from the nominal file.")
    w("- **Byte-identity gate:** the nominal path with all flags off "
      "reproduces the PRE-change reference (generated by "
      "`lc2_nominal_ref.py` through the untouched "
      "`eval_a2.window_rows` BEFORE the engine edit) byte-identically "
      "- canonical-json equality on all 140 v2g rows of the first two "
      "panel worlds (pre-flight gate in `run_lc2.py`, real stdout in "
      "`results/lc2_run.out`; pytest "
      "`test_nominal_byte_identity_vs_prechange_reference`). The full "
      "nominal run also reproduces the frozen post-LC1 A2 aggregates "
      "exactly (all H: merge/disc pred+true counts and s_RMSE means "
      "equal to `results/eval_a2_post_lc1/summary.json`).")
    w(f"- **TRAIN only:** plan split asserted per world before any "
      f"run-file open; {len(meta['opened_run_files'])} opened files "
      f"recorded (`lc2_opened_run_files.json`), "
      f"`assert_train_only` passed; CALIBRATION/VALIDATION/HOLDOUT "
      f"never opened.")
    w(f"- **Budget:** zero SUMO; wall {meta['wall_clock_s']:.0f} s at "
      f"{meta['workers']} workers (<= 3 per task constraint).")
    w("- **Delay-scope note (owner decision (c)):** Part A is "
      "TRACKED-scope; Part B carries untracked arrivals. Every number "
      "below is a tracked-cohort quantity and says nothing about "
      "system delay.")
    w("")
    w("## 1. Variant specs and provenance")
    w("")
    w("All four are implemented in `partA_v2g/engine.py` behind the "
      "injected `lc_variants` section with the default OFF; unit "
      "tests in `partA_v2g/tests/test_lc2_variants.py` (13 tests, "
      "green): V-a fires only after 4 consecutive qualifying steps "
      "(and resets on a broken chain); V-b blocks discretionary "
      "changes for exactly 4.0 s after any change while mandatory "
      "merges stay ungated; V-c applies zero threshold + 1.0 m/s^2 "
      "bias from the zone start with the safety test unchanged; the "
      "flags-off engine path is identical to the nominal parameters.")
    w("")
    for v in ("va", "vb", "vc"):
        name, spec = VARIANT_SPECS[v]
        w(f"- **{name}:** {spec}")
    w("- **V-abc:** all three combined.")
    w("")
    w("## 2. Per variant x H table")
    w("")
    w("Means over the covered window rows (n = worlds with that H "
      "covered; 32 everywhere); LC ratios are POOLED predicted/true "
      "counts (the registration's convention, matching Table 1' of "
      "DIAGNOSIS_LC1.md); dwell median / early-edge share / stops are "
      "computed within the H horizon over the tracked cohort "
      "(early edge: merge event at s < 415 m; dead-end stop: tracked "
      "accel-lane vehicle at s >= s1z-0.51 with v < 0.1 within H - a "
      "window-level convention, NOT LC1's whole-run census, so the "
      "constant 72 counts pre-existing stopped vehicles at w); "
      "collisions per 1000 predicted vehicle-steps; ttc3err/harderr "
      "are the signed mean predicted-minus-true errors (s).")
    w("")
    w("| variant|H | s_RMSE | v_RMSE | delay err (signed) | delay MAE "
      "| disc p/t (ratio) | merge p/t (ratio) | dwell med s | early% "
      "| stops | coll/1000 | TTC<3 err | hard-brake err |")
    w("|---|---|---|---|---|---|---|---|---|---|---|---|---|")
    for var in ("nominal",) + VARIANTS:
        for H in HS:
            a = tab[f"{var}|H{H}"]
            w(f"| {var}|H{H} | {fmt(a['s_rmse'])} | {fmt(a['v_rmse'])} "
              f"| {fmt(a['delay_err_mean'])} | {fmt(a['delay_err_mae'])} "
              f"| {a['disc_p']}/{a['disc_t']} ({a['disc_ratio']:.2f}x) "
              f"| {a['merge_p']}/{a['merge_t']} "
              f"({a['merge_ratio']:.2f}x) "
              f"| {fmt(a['dwell_median'], 1)} "
              f"| {100*a['early_edge_share']:.1f} | {a['stops']} "
              f"| {fmt(a['coll_per_1000'])} "
              f"| {fmt(a['ttc3_err_mean'], 2)} "
              f"| {fmt(a['hard_err_mean'], 2)} |")
    w("")
    w("Nominal cross-check: the nominal rows above equal the frozen "
      "post-LC1 A2 headline (disc 4.60x/5.50x/5.99x/5.22x; merge "
      "0.66x/0.37x/0.75x/0.92x at H10/H30/H60/H120) - the harness "
      "and counting are the registered ones.")
    w("")
    w("## 3. World-bootstrap 90 % CIs of variant - nominal "
      "differences")
    w("")
    w(f"World bootstrap (B = {s['b_boot']}, seed {s['seed']}, "
      f"resampling the 32 worlds with replacement; per-H relative "
      f"differences for s_RMSE / v_RMSE / delay MAE, absolute "
      f"differences otherwise; 5th-95th percentile):")
    w("")
    w("| variant|H | rel d(s_RMSE) [90% CI] | rel d(v_RMSE) | rel "
      "d(delay MAE) | d(disc ratio) | d(merge ratio) | d(dwell med) "
      "| d(early share) | d(stops) | d(coll/1000) |")
    w("|---|---|---|---|---|---|---|---|---|---|")
    for var in VARIANTS:
        for H in HS:
            c = cis[var][f"H{H}"]

            def fci(key, nd=3):
                v = c[key]
                return (f"[{v[0]:+.{nd}f}, {v[1]:+.{nd}f}]"
                        if v else "-")
            a = tab[f"{var}|H{H}"]
            n_ = tab[f"nominal|H{H}"]
            rel_s = (a["s_rmse"] - n_["s_rmse"]) / n_["s_rmse"]
            w(f"| {var}|H{H} | {rel_s:+.3f} {fci('rel_s_rmse')} "
              f"| {fci('rel_v_rmse')} | {fci('rel_delay_mae')} "
              f"| {fci('disc_ratio_diff')} | {fci('merge_ratio_diff')} "
              f"| {fci('dwell_diff', 1)} | {fci('early_share_diff')} "
              f"| {fci('stops_diff', 1)} | {fci('coll1000_diff')} |")
    w("")
    w("## 4. Pre-registered decision rule, applied verbatim")
    w("")
    w("Registered rule (section 4 of the registration, quoted): a "
      "variant is a **BIG IMPROVEMENT** iff benefit AND no-harm hold. "
      "Benefit: (a) s_RMSE at H=30 AND H=60 each >= 20 % lower than "
      "nominal with the world-bootstrap 90 % CI of the relative "
      "change excluding 0, OR (b) disc-LC ratio at H30 in [0.67, "
      "1.5] AND merge-LC ratio at H30 in [0.67, 1.5]. No harm: H10 "
      "and H30 s_RMSE not worse than nominal by more than 5 %; H30 "
      "delay MAE not worse by more than 10 %; collisions <= nominal "
      "+ 0.1 per 1000 veh-steps. Otherwise MODEST if benefit is only "
      "partly met and no-harm holds, NO IMPROVEMENT otherwise.")
    w("")
    w("Operationalization (documented, fixed before running): "
      "'relative change' = (variant - nominal)/nominal of the "
      "window-mean s_RMSE (the summary.json convention); 'CI "
      "excluding 0' counted only when the point estimate is an "
      "improvement; 'partly met' = at least one RMSE sub-condition "
      "(one horizon at >= 20 % lower with its CI excluding 0, or "
      "both horizons >= 20 % lower without BOTH CIs excluding 0) or "
      "exactly one of the two H30 ratios inside its band; no-harm "
      "point estimates as registered (the rule attaches no CI to "
      "them), with the collision clause evaluated at H30 (and "
      "reported at every H in the table above, all within the "
      "nominal + 0.1 bound).")
    w("")
    w("| variant | rel s_RMSE H10 / H30 / H60 | CI H30 excl 0 (rel) "
      "| CI H60 excl 0 (rel) | rel delay MAE H30 | coll/1000 "
      "var vs nom | rmse crit | ratio crit (disc, merge @H30) | "
      "no-harm | verdict |")
    w("|---|---|---|---|---|---|---|---|---|---|")
    for var in VARIANTS:
        d = dec[var]
        c30 = cis[var]["H30"]["rel_s_rmse"]
        c60 = cis[var]["H60"]["rel_s_rmse"]
        t30, n30 = tab[f"{var}|H30"], tab["nominal|H30"]
        w(f"| {var} | {d['rel_s_rmse_H10']:+.3f} / "
          f"{d['rel_s_rmse_H30']:+.3f} / {d['rel_s_rmse_H60']:+.3f} "
          f"| {'yes' if d['ci_H30_excludes_0'] else 'no'} "
          f"[{c30[0]:+.3f}, {c30[1]:+.3f}] "
          f"| {'yes' if d['ci_H60_excludes_0'] else 'no'} "
          f"[{c60[0]:+.3f}, {c60[1]:+.3f}] "
          f"| {d['rel_delay_mae_H30']:+.3f} "
          f"| {t30['coll_per_1000']:.3f} vs {n30['coll_per_1000']:.3f} "
          f"| {'MET' if d['rmse_criterion'] else 'not met'} "
          f"| {'MET' if d['ratio_criterion'] else 'not met'} "
          f"({t30['disc_ratio']:.2f}x, {t30['merge_ratio']:.2f}x) "
          f"| {'yes' if d['no_harm'] else 'NO'} "
          f"| **{d['verdict']}** |")
    w("")
    w("Reading: no variant reaches even one full benefit component. "
      "The best RMSE movement (va -8.8 % and vabc -8.4 % at H30, CI "
      "excluding 0) is far from the required -20 %, and both leave "
      "the H30 LC ratios essentially unmoved (disc ~4.4x vs required "
      "[0.67, 1.5]; merge 0.35-0.43x vs required [0.67, 1.5]). V-b "
      "slightly WORSENS s_RMSE. V-c moves merging in the registered "
      "direction (H30 merge ratio 0.37x -> 0.46x, early merges and "
      "H10 merge counts up, dwell down at H30/H120) at a small "
      "collision cost (0.029 -> 0.035 per 1000 at H30, still <= "
      "nominal + 0.1) but nowhere near the ratio band and with no "
      "RMSE benefit. V-b's manoeuvre-time block mostly reorders "
      "which vehicle fires (the block suppresses the second change "
      "of a pair within 4 s) and does not reduce the production "
      "rate.")
    w("")
    w("## 5. Recommendation")
    w("")
    if s["recommendation"] == "keep textbook":
        w("**Keep textbook (owner option 1).** No variant is a BIG "
          "IMPROVEMENT, so per the registered recommendation rule "
          "option 2 is NOT worth registering on this evidence, and "
          "no smallest BIG variant exists. The residual disc "
          "over-production and short-H merge lag remain characterized "
          "model error of textbook MOBIL/merge at dt = 0.5 s "
          "(DIAGNOSIS_LC1.md section 6, option 1).")
    else:
        w(f"**{s['recommendation']}.**")
    w("")
    w("Caveat (registered up front): TRAIN-only evidence with a "
      "priori values. A variant adopted later needs fresh evaluation "
      "worlds, because C4L1 consumes the chunk-4 CAL for the nominal "
      "model. Nothing was adopted or selected here; "
      "params_nominal.json is unchanged.")
    w("")
    w("## 6. Provenance and artifacts")
    w("")
    w("- Registration: `output/wd01/REGISTRATION_PA2G_LC2.md` "
      "(LF-sha256 725e0a876c554d7b...).")
    w("- Scripts (`output/wd01/partA_v2g/`): `lc2_nominal_ref.py` "
      "(pre-change reference), `run_lc2.py` (identity gate + 5 "
      "configs x 32 worlds), `lc2_tables.py` (aggregation + "
      "bootstrap + decision rule), `lc2_report.py` (this report), "
      "engine flags in `engine.py`, variant config `variants_lc2.json` "
      "+ loader `variants.py`.")
    w("- Raw rows BEFORE aggregation: `results/lc2/lc2_rows.jsonl` "
      f"({meta['raw_rows']}), `results/lc2/lc2_merge_outcomes.jsonl` "
      f"({meta['merge_rows']}); pre-change reference "
      "`results/lc2/nominal_ref_prechange.jsonl` (140 rows, frozen "
      "before the engine edit); aggregates `results/lc2/"
      "lc2_summary.json`; run logs `results/lc2_run.out`, "
      "`results/lc2_tables.out`; smoke/wiring "
      "`results/lc2_smoke/`.")
    w("- TRAIN only: opened-file list "
      "`results/lc2/lc2_opened_run_files.json` "
      f"({len(meta['opened_run_files'])} files), "
      "`assert_train_only` passed at close-out; the plan split was "
      "asserted per world before any open.")
    w("- Ledger draft: `output/wd01/LEDGER_DRAFT_PA2G_LC2.json`.")
    w("")
    OUT.write_text("\n".join(L) + "\n", encoding="utf-8")
    print(f"wrote {OUT} ({len(L)} lines)")


if __name__ == "__main__":
    main()
