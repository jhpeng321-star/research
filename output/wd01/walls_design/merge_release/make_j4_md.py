"""Render J4_MERGE_ANALYSIS.md from j4_merge_analysis.json (zero SUMO)."""
from __future__ import annotations

import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
DATA = json.load(open(os.path.join(HERE, "j4_merge_analysis.json"),
                      encoding="utf-8"))
R = DATA["report"]
C = R["constants"]


def d(dd):
    if not dd or dd.get("n", 0) == 0:
        return "n=0"
    return (f"n={dd['n']} min={dd['min']} p25={dd['p25']} "
            f"med={dd['median']} p75={dd['p75']} max={dd['max']} "
            f"mean={dd['mean']}")


L = []
L.append("# J4 wall-pilot MERGE analysis (mechanism-only; zero SUMO; law v2.2 design input)")
L.append("")
L.append("Generated by `j4_merge_analysis.py` from "
         "`E:/research-dense/runs/campaign_walls_pilot_chunk4`. "
         "This document reads **no outcome field**: no `evaluate_summary`, "
         "`suffix_summary`, delay/TTC metric or physics outcome summary is "
         "opened. It reads only (a) `run/wall_events.jsonl` request / "
         "assembly / hold / release / abort timestamps and member ids / lane "
         "ids, (b) `run/branch_record.json` lifecycle classification, and "
         "(c) the RAW `vehicles` positions (road_id + lane_position_m) in "
         "`run/physics_steps.jsonl`, used exclusively to locate members on the "
         "road coordinate. No HOLDOUT and no CALIBRATION world was opened: the "
         "split comes from the chunk-4 wall plan (`WORLD_PLAN.json`) and only "
         "its TRAIN worlds were processed.")
L.append("")
L.append("## 1. Road coordinate and geometry (edge-aware `s_road`)")
L.append("")
L.append("The live rule (`wall_request.py:119`) assumes `frame.position_m` is a "
         "position on the entry edge. It is not: `position_m` is the position "
         "on the member's CURRENT lane/edge. v2.2 replaces it with the "
         "cumulative edge-aware coordinate `s_road` below.")
L.append("")
L.append("| edge | role | length (m) | `s_road` |")
L.append("| --- | --- | ---: | --- |")
L.append(f"| 1191554636 | mainline ENTRY (no incoming) | {C['entry_len_m']} "
         f"| `position_m` |")
L.append(f"| 1487606179 | MERGE | {C['merge_len_m']} "
         f"| {C['merge_start_s']} + `position_m` |")
L.append(f"| 1487606178 | EXIT | {C['exit_len_m']} "
         f"| {C['merge_end_s']} + `position_m` |")
L.append(f"| internal `:` | junction | - | {C['merge_start_s']} - "
         "`distance_to_merge_m` |")
L.append("")
L.append(f"MERGE START `s_road` = **{C['merge_start_s']} m**; merge end = "
         f"{C['merge_end_s']} m; network end = {C['net_end_s']} m.")
L.append("")
L.append("## 2. Funnel (TRAIN worlds only)")
L.append("")
L.append(f"- scan dirs: {R['n_dirs']}; TRAIN branch dirs: {R['n_train']} "
         f"(39 TRAIN worlds x 4 arms); CALIBRATION/HOLDOUT skipped: "
         f"{R['skipped_cal_or_holdout']}.")
L.append(f"- wall requests: **{R['n_requested']}**; `not_feasible`: "
         f"{R['n_not_feasible']}.")
for k, v in sorted(R["outcomes"].items()):
    L.append(f"- outcome `{k}`: {v}.")
L.append(f"- abort reasons: "
         + ", ".join(f"`{k}`={v}" for k, v in sorted(R["abort_reasons"].items()))
         + ".")
L.append("")
L.append("## 3. `s_road` (lead member) at each lifecycle phase")
L.append("")
L.append("| phase / metric | distribution (m) |")
L.append("| --- | --- |")
L.append(f"| request | {d(R['s_road_request'])} |")
L.append(f"| assembled | {d(R['s_road_assembled'])} |")
L.append(f"| finish (release or abort) | {d(R['s_road_finish'])} |")
L.append(f"| distance to merge at request | {d(R['distance_to_merge_request'])} |")
L.append(f"| distance to merge at finish | {d(R['distance_to_merge_finish'])} |")
L.append(f"| wall speed (m/s) | {d(R['wall_speed_mps'])} |")
L.append(f"| assembly time (s) | {d(R['assembly_time_s'])} |")
L.append(f"| requested span (m) | {d(R['span_m'])} |")
L.append("")
L.append(f"Lead-member `s_road` at finish was resolvable for all "
         f"{R['n_requested']} requests (`n_finish_s_road_missing` = "
         f"{R['n_finish_s_road_missing']}); members that left the network are "
         "located at their last pre-departure position.")
L.append("")
L.append("## 4. Hold continuation past the merge and the exit")
L.append("")
L.append(f"- walls whose hold was still active with the lead member at or "
         f"past the MERGE START (`s_road` >= {C['merge_start_s']}): "
         f"**{R['n_held_past_merge_start']}** of {R['n_requested']} requests "
         f"({round(100.0 * R['n_held_past_merge_start'] / R['n_requested'], 1)} %).")
L.append(f"- walls whose hold continued into the EXIT edge "
         f"(`s_road` >= {C['merge_end_s']}): **{R['n_held_into_exit']}**.")
L.append("")
L.append("By registered fixed-arm hold draw:")
L.append("")
L.append("| hold H (s) | requests | assembled | past merge start | into exit |")
L.append("| ---: | ---: | ---: | ---: | ---: |")
for hold in ("60", "120", "240"):
    b = R["by_hold"][hold]
    L.append(f"| {hold} | {b['n']} | {b['s_road_finish']['n']} | "
             f"{b['n_held_past_merge_start']} | {b['n_held_into_exit']} |")
L.append("")
L.append("## 5. `s_road` at each abort reason")
L.append("")
L.append("| abort reason | n | s_road at finish | s_road at request | wall speed (m/s) |")
L.append("| --- | ---: | --- | --- | --- |")
for reason in ("member_left_network", "member_span_exceeded",
               "non_member_rear_end_risk", "lane_coverage_violation",
               "assembly_timeout"):
    if reason not in R["abort_detail"]:
        L.append(f"| {reason} | 0 | - | - | - |")
        continue
    a = R["abort_detail"][reason]
    L.append(f"| {reason} | {a['n']} | {d(a['s_road_finish'])} | "
             f"{d(a['s_road_request'])} | {d(a['wall_speed_mps'])} |")
L.append("")
L.append("Reading: `member_left_network` finishes at `s_road` ~3195 m on "
         "average, i.e. at the network end - the J4 hold ran all the way to "
         "the road end and the wall was truncated there (the broken road-end "
         "behaviour v2.2 replaces). `member_span_exceeded` finishes around "
         "2786 m (in the exit edge) for the fastest walls. "
         "`non_member_rear_end_risk` covers a wide range including upstream "
         "aborts.")
L.append("")
L.append("## 6. Would the v2.2 proposer have accepted these requests?")
L.append("")
dm = R["dmin"]
L.append(f"`D_min = X + v_wall * t_assemble + v_wall * H_min` with the owner "
         f"binding `X = {dm['X_m']} m` and `H_min = {dm['H_min_s']} s` "
         "(the smallest registered fixed-arm hold), using each J4 request's "
         "measured wall speed and assembly time (a-priori, no outcome).")
L.append("")
L.append(f"- requests scored: {dm['n']}; feasible under D_min "
         f"(`distance_to_merge(request) >= D_min`): **{dm['n_feasible']}** "
         f"({round(100.0 * dm['n_feasible'] / dm['n'], 1)} %).")
L.append(f"- D_min (m): {d(dm['dmin_m'])}.")
L.append(f"- margin `distance_to_merge(request) - D_min` (m): "
         f"{d(dm['margin_m'])}.")
L.append("")
L.append("## 7. Verdict")
L.append("")
L.append(f"**J4 = 'walls held through the merge'.** {R['n_held_past_merge_start']} "
         f"of {R['n_requested']} J4 wall requests finished their hold at or "
         f"past the merge start, {R['n_held_into_exit']} of them inside the "
         "477.9 m exit edge, and the `member_left_network` aborts sit at "
         f"`s_road` ~3195 m (the network end). Walls did not stop before the "
         "merge; the old planner only released at the road end (A4), which is "
         "the defect v2.2's fixed MERGE-RELEASE point replaces.")
L.append("")

with open(os.path.join(HERE, "J4_MERGE_ANALYSIS.md"), "w",
          encoding="utf-8", newline="\n") as fh:
    fh.write("\n".join(L))
print("wrote J4_MERGE_ANALYSIS.md", len(L), "lines")
