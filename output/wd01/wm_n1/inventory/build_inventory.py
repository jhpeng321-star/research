"""CLI: build the WM-N1 corpus inventory + size estimate (metadata only).

    python build_inventory.py --data-root E:/research-dense --out <dir>

Never touches D:, never runs SUMO, reads physics content only for a timed
micro-sample of at most three TRAIN runs.
"""
from __future__ import annotations

import argparse
import json
import os
import sys
from pathlib import Path

import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parent))
import inventory_lib as inv  # noqa: E402


def _lower_priority():
    """Best-effort BELOW_NORMAL priority class (single metadata-only worker)."""
    if os.name != "nt":
        return
    try:
        import ctypes

        below_normal = 0x00004000
        handle = ctypes.windll.kernel32.GetCurrentProcess()
        ctypes.windll.kernel32.SetPriorityClass(handle, below_normal)
    except Exception:  # noqa: BLE001 - priority etiquette is best-effort
        pass


def _install_forbid_d():
    if os.environ.get("WD_FORBID_D", "").strip() != "1":
        return
    hook = Path(__file__).resolve().parents[2] / "forbid_d_hook.py"
    if not hook.is_file():
        return
    sys.path.insert(0, str(hook.parent))
    import forbid_d_hook
    forbid_d_hook.install()


def _human(n):
    if n is None:
        return "n/a"
    for unit in ("B", "KiB", "MiB", "GiB", "TiB"):
        if abs(n) < 1024.0:
            return f"{n:.2f} {unit}"
        n /= 1024.0
    return f"{n:.2f} PiB"


def _render_md(data_root, df, pairs, micro, est, refused, holdout_names, guard):
    lines = []
    lines.append("# WM-N1 corpus inventory and size estimate\n")
    lines.append("Data root: `%s`  " % data_root)
    lines.append("Generated by `output/wd01/wm_n1/inventory/build_inventory.py` "
                 "(metadata-only; zero SUMO).\n")

    lines.append("## 1. Runs enumerated (TRAIN/CAL)\n")
    lines.append(f"- TRAIN runs: {est['train_runs']}")
    lines.append(f"- CAL runs: {est['cal_runs']}")
    lines.append(f"- total TRAIN/CAL runs: {est['train_runs'] + est['cal_runs']}")
    lines.append(f"- HOLDOUT runs counted by NAME only (never opened): {len(holdout_names)}\n")

    lines.append("### per chunk / split (present runs)\n")
    lines.append("| chunk | TRAIN | CAL |")
    lines.append("| --- | --- | --- |")
    for chunk in sorted(est["per_chunk"], key=lambda c: str(c)):
        row = est["per_chunk"][chunk]
        lines.append(f"| {chunk} | {row['TRAIN']} | {row['CALIBRATION']} |")

    lines.append("\n### per policy (present runs)\n")
    lines.append("| policy | TRAIN | CAL |")
    lines.append("| --- | --- | --- |")
    for pol in sorted(est["per_policy"]):
        row = est["per_policy"][pol]
        lines.append(f"| {pol} | {row['TRAIN']} | {row['CALIBRATION']} |")

    lines.append("\n## 2. Policy pairs (contrast-loss siblings)\n")
    lines.append("Pair key = world + t0; the reference arm is the genuine "
                 "`native` arm (J3 truearms / chunk-4 native), and each pair "
                 "links it to one sibling policy arm.  `same_base_state` is "
                 "True when both receipts carry an equal `saved_state_id`, "
                 "False when they differ, and `?` when a full-run base carries "
                 "no saved_state_id (unverifiable from metadata).\n")
    lines.append("| pair category | count | same base | differs | unknown |")
    lines.append("| --- | --- | --- | --- | --- |")
    cat = {}
    for p in pairs:
        c = cat.setdefault(p["category"], {"n": 0, "same": 0, "diff": 0, "unk": 0})
        c["n"] += 1
        if p["same_base_state"] is True:
            c["same"] += 1
        elif p["same_base_state"] is False:
            c["diff"] += 1
        else:
            c["unk"] += 1
    for category in sorted(cat):
        c = cat[category]
        lines.append(f"| {category} | {c['n']} | {c['same']} | {c['diff']} | {c['unk']} |")
    if not cat:
        lines.append("| (none) | 0 | 0 | 0 | 0 |")
    lines.append(f"\nTotal pairs: {len(pairs)}\n")

    lines.append("## 3. Micro-sample (timed, <= 3 TRAIN runs)\n")
    lines.append(f"- runs sampled: {', '.join(micro['runs']) or 'none'}")
    lines.append(f"- lines read: {micro['lines_read']}")
    lines.append(f"- mean vehicles/tick: {micro['vehicles_per_tick_mean']:.2f}")
    lines.append(f"- max vehicles/tick: {micro['vehicles_per_tick_max']}")
    lines.append(f"- p95 vehicles/tick: {micro['vehicles_per_tick_p95']:.2f}")
    lines.append(f"- parse time: {micro['parse_seconds']:.3f} s; "
                 f"featurize time: {micro['featurize_seconds']:.3f} s")
    lines.append(f"- featurization throughput: {micro['ticks_per_second']:.1f} ticks/s "
                 f"(single process)")
    lines.append(f"- zstd ratio on sample features: {micro['zstd_ratio']:.4f} "
                 f"({_human(micro['sample_raw_bytes'])} -> "
                 f"{_human(micro['sample_compressed_bytes'])})\n")

    lines.append("## 4. Tick and memmap size estimate\n")
    lines.append(f"- TRAIN ticks: {est['train_ticks']:,}")
    lines.append(f"- CAL ticks: {est['cal_ticks']:,}")
    lines.append(f"- total 0.5 s ticks: {est['total_ticks']:,}")
    lines.append(f"- decision times (30 s): {est['n_decisions']:,}")
    lines.append(f"- raw physics JSONL on disk: {_human(est['physics_raw_bytes'])}\n")
    lines.append(f"Vehicle-step tensor [N_ticks, K_max={est['k_max']}, "
                 f"F={est['n_features']}, float16]: {_human(est['veh_bytes'])}")
    lines.append(f"Masks [N_ticks, K_max, float16]: {_human(est['mask_bytes'])}")
    lines.append(f"Plan tensor [N_dec, K_max, 20 segments, int8]: {_human(est['plan_bytes'])}")
    lines.append(f"Counter tensor [N_dec, 30 bins, 2 entrances, float16]: "
                 f"{_human(est['counter_bytes'])}")
    lines.append(f"Total (vehicle+mask+plan+counter): {_human(est['tensor_bytes'])}")
    lines.append(f"zstd estimate (vehicle+mask tensors at sample ratio): "
                 f"{_human(est['zstd_bytes'])}\n")
    wall = est["wall_hours_4_workers"]
    lines.append(f"- featurization wall-time at {est['workers']} workers: "
                 f"{'n/a' if wall is None else f'{wall:.2f} h'}\n")

    lines.append("## 5. Refused / incomplete runs\n")
    lines.append(f"- total refused/incomplete: {len(refused)}\n")
    if refused:
        lines.append("| batch | world | run | reason |")
        lines.append("| --- | --- | --- | --- |")
        for r in refused[:200]:
            lines.append(f"| {r['batch']} | {r['world']} | {r['run']} | {r['reason']} |")
        if len(refused) > 200:
            lines.append(f"\n({len(refused)} total; see refused_runs.json)\n")
    else:
        lines.append("None.\n")

    lines.append("## 6. HOLDOUT accounting (by name only)\n")
    lines.append(f"- HOLDOUT runs counted by name from plans: {len(holdout_names)}")
    lines.append(f"- excluded worlds (holdout_exclusions.json): {len(guard.excluded)}")
    lines.append(f"- kept_disclosed worlds: {', '.join(guard.disclosed) or 'none'}")
    lines.append("- No HOLDOUT directory was listed or opened; asserted in the "
                 "opened-path audit.\n")

    lines.append("## 7. Opened-path audit\n")
    lines.append(f"- files opened: {len(guard.opened)}")
    lines.append("- HOLDOUT token in any opened path: NO")
    lines.append("- dispatcher_rows.jsonl / insertions.jsonl opened: NO\n")
    return "\n".join(lines) + "\n"


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--data-root", default="E:/research-dense")
    parser.add_argument("--out", default=str(Path(__file__).resolve().parent))
    parser.add_argument("--micro-runs", type=int, default=3)
    parser.add_argument("--micro-lines", type=int, default=400)
    parser.add_argument("--workers", type=int, default=4)
    parser.add_argument("--k-max", type=int, default=inv.K_MAX)
    parser.add_argument("--features", type=int, default=inv.N_FEATURES)
    args = parser.parse_args(argv)
    _install_forbid_d()
    _lower_priority()

    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)

    guard = inv.make_guard(args.data_root)
    rows, holdout_names, planned = inv.build_rows(args.data_root, guard)
    df = pd.DataFrame(rows)
    pairs = inv.build_pairs(df)
    refused = inv.incomplete_runs(rows)

    tokens = set(guard.excluded) | set(guard.disclosed)
    tokens |= {h["world"] for h in holdout_names}
    guard.assert_clean(tokens)

    micro = inv.micro_sample(rows, args.data_root, guard,
                             n_runs=args.micro_runs, max_lines=args.micro_lines,
                             k_max=args.k_max, n_features=args.features)
    est = inv.estimate_sizes(rows, micro, workers=args.workers,
                             k_max=args.k_max, n_features=args.features)
    guard.assert_clean(tokens)

    df.to_parquet(out / "inventory.parquet", index=False)
    pd.DataFrame(pairs).to_parquet(out / "pairs.parquet", index=False)
    (out / "opened_paths.json").write_text(
        json.dumps({"count": len(guard.opened), "paths": guard.opened}, indent=1),
        encoding="utf-8")
    (out / "holdout_names.json").write_text(
        json.dumps({"runs": holdout_names, "excluded": sorted(guard.excluded),
                    "kept_disclosed": guard.disclosed}, indent=1),
        encoding="utf-8")
    (out / "refused_runs.json").write_text(
        json.dumps(refused, indent=1), encoding="utf-8")
    summary = {"data_root": args.data_root, "train_runs": est["train_runs"],
               "cal_runs": est["cal_runs"], "total_ticks": est["total_ticks"],
               "pairs": len(pairs), "holdout_runs_by_name": len(holdout_names),
               "refused": len(refused), "opened_paths": len(guard.opened)}
    (out / "summary.json").write_text(json.dumps(summary, indent=1), encoding="utf-8")
    (out / "SIZE_ESTIMATE.md").write_text(
        _render_md(args.data_root, df, pairs, micro, est, refused,
                   holdout_names, guard), encoding="utf-8")

    print(json.dumps(summary, indent=1))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
