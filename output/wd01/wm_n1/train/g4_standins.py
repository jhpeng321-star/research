"""Deterministic CPU stand-ins + tiny TRAIN windows for the G4 overfit gate.

The owner pre-flight G4 gate (``PREFLIGHT_GATES_IDEA_A.md``) asks that a single
Idea A member drive the *total* A3.2 loss (residual NLL, rollout, arrival,
correction CRPS and the paired response contrast) near zero on two tiny TRAIN
windows, on CPU.  This is a machinery check of the P7 loss assembly and
optimiser; the P7 gate test
(``train/tests/test_idea_a_overfit.py``) exercises it with these deterministic
stand-ins.

They are deliberately tiny linear CPU nets that consume P2/P4/P5 ONLY through
their INTERFACES_V2 forward signatures, so no real attention net or data is
needed.  The windows are labelled ``split="TRAIN"`` sibling pairs (treatment +
all-native reference) whose targets are generated by the same equations the
losses fit, so a member can reach the ~zero floor.  No SUMO, no real corpus.

Documented fallback — FAILS the owner gate (integration stage 3)
----------------------------------------------------------------
The headline G4 gate now runs the REAL modules
(:func:`train.idea_a.overfit_report`, ``train.g4_real``): the real
:class:`hdv.net.HdvResidualNet`, :class:`arrival.head.IdeaAArrivalHead` and
:class:`corr.head.CorrectionHead` (with the real 64-d
:class:`corr.summary.CavMotionSummary` projection), each in a tiny-but-real
config, on two tiny TRAIN windows.  The linear nets below are kept ONLY as a
documented fallback: if :func:`train.idea_a.overfit_report` is called with
``standins=True`` (or is handed a bundle from :func:`seeded_bundle`), the
report is forced to ``ok=False`` with a warning, because it proves only the P7
loss-assembly machinery and not the real P2/P4/P5 forward/backward path the
owner gate requires.

The tiny windows (:func:`make_windows`) are shared by both paths; the real
bundle consumes the same canonical batch (16-d ``summary_raw`` in, 64-d
projected summary inside the real P5 composition).

They are deliberately tiny linear CPU nets that consume P2/P4/P5 ONLY through
their INTERFACES_V2 forward signatures, so no real attention net or data is
needed.  The windows are labelled ``split="TRAIN"`` sibling pairs (treatment +
all-native reference) whose targets are generated by the same equations the
losses fit, so a member can reach the ~zero floor.  No SUMO, no real corpus.
"""
from __future__ import annotations

from types import SimpleNamespace

import torch
import torch.nn as nn
import torch.nn.functional as F

import train.idea_a as ia
from model import constants as C

KIN_F = 7
SUMMARY_RAW_F = 16
CORR_D_MODEL = 16
OUT_SCALE = 20.0


class G4Hdv(nn.Module):
    """``HdvResidualNet`` stand-in: kin [B,K,7] -> accel delta + lane logits."""

    G4_STANDIN = True

    def __init__(self, hidden: int = 16, accel_delta_scale_mps2: float = 1.5):
        super().__init__()
        self.cfg = SimpleNamespace(accel_delta_scale_mps2=accel_delta_scale_mps2)
        self.net = nn.Sequential(nn.Linear(KIN_F, hidden), nn.GELU(),
                                 nn.Linear(hidden, 4))
        nn.init.zeros_(self.net[-1].weight)
        nn.init.zeros_(self.net[-1].bias)

    def forward(self, kin: torch.Tensor, kin_mask: torch.Tensor, *,
                cav_flag=None) -> dict:
        if kin.shape[-1] > KIN_F:
            raise ValueError("headline HDV net accepts kinematics only")
        out = self.net(kin)
        keep = kin_mask.float()
        return {"accel_delta_mps2": out[..., 0] * keep,
                "lane_logit_delta": out[..., 1:4] * keep.unsqueeze(-1)}


class G4Arrival(nn.Module):
    """``IdeaAArrivalHead`` stand-in: counter [B,2,30] -> the four [B,2]."""

    G4_STANDIN = True

    def __init__(self, hidden: int = 16):
        super().__init__()
        self.net = nn.Sequential(nn.Linear(2 * C.COUNTER_BINS, hidden),
                                 nn.GELU(), nn.Linear(hidden, 8))
        nn.init.zeros_(self.net[-1].weight)
        nn.init.zeros_(self.net[-1].bias)

    def forward(self, counter: torch.Tensor) -> dict:
        out = self.net(counter.flatten(1))
        return {"count_mu": F.softplus(out[:, 0:2]),
                "count_log_alpha": out[:, 2:4],
                "speed_mu": out[:, 4:6],
                "speed_log_sigma": out[:, 6:8]}


class G4Corr(nn.Module):
    """``CorrectionHead`` stand-in: (summary, token) -> quantiles + logits."""

    G4_STANDIN = True

    def __init__(self, hidden: int = 24):
        super().__init__()
        self.cfg = SimpleNamespace(d_model=CORR_D_MODEL)
        self.net = nn.Sequential(
            nn.Linear(SUMMARY_RAW_F + CORR_D_MODEL, hidden), nn.GELU(),
            nn.Linear(hidden, C.N_TAU * C.N_OUTCOME_TARGETS * C.N_QUANTILES))
        nn.init.zeros_(self.net[-1].weight)
        nn.init.zeros_(self.net[-1].bias)
        self.collision = nn.Linear(SUMMARY_RAW_F + CORR_D_MODEL, C.N_TAU)

    def forward(self, summary: torch.Tensor,
                global_token: torch.Tensor) -> dict:
        z = torch.cat([summary, global_token], dim=-1)
        q = self.net(z).view(-1, C.N_TAU, C.N_OUTCOME_TARGETS,
                             C.N_QUANTILES) * OUT_SCALE
        return {"outcome_quantiles": q,
                "collision_logits": self.collision(z)}


def seeded_bundle(seed: int = 101) -> ia.IdeaABundle:
    torch.manual_seed(int(seed))
    return ia.IdeaABundle(hdv=G4Hdv(), arrival=G4Arrival(), corr=G4Corr())


def make_windows(n_windows: int = 2, k: int = 8, seed: int = 0,
                 horizon: int = 3) -> list:
    """Tiny paired-arm TRAIN windows (treatment, reference) per window."""
    g = torch.Generator().manual_seed(seed)
    slots = torch.arange(k, dtype=torch.float32)
    base_v = 6.0 + 0.75 * slots
    lane_idx = (slots.long() % C.N_LANES).float()
    windows = []
    for w in range(n_windows):
        arm = torch.tensor([[1.0], [0.0]])
        true_accel = 0.4 * torch.sin(slots * 1.3).unsqueeze(0) + 0.3 * arm
        baseline_idm = -0.1 * (slots - k / 2.0)
        s0 = (-100.0 + 20.0 * slots).unsqueeze(0).repeat(2, 1) + 0.25 * w
        v0 = base_v.unsqueeze(0).repeat(2, 1)
        a0 = true_accel
        lane0 = lane_idx.unsqueeze(0).repeat(2, 1)
        length0 = torch.full((2, k), float(C.NOMINAL_LENGTH_M))
        one_hot = F.one_hot(lane0.long(), C.N_LANES).float()
        kin = torch.stack([s0, one_hot[..., 0], one_hot[..., 1],
                           one_hot[..., 2], v0, a0, length0], dim=-1)
        is_cav = torch.zeros(2, k, dtype=torch.bool)
        is_cav[:, :2] = True
        target_mask = torch.ones(2, k, dtype=torch.bool)
        target_accel = baseline_idm.unsqueeze(0) + true_accel
        lane_target = torch.full((2, k), -1, dtype=torch.long)
        lane_target[:, 2] = 1
        counter = torch.rand(2, C.N_ENTRANCES, C.COUNTER_BINS, generator=g)
        arrivals = torch.zeros(2, C.N_ENTRANCES)
        summary_raw = torch.rand(2, SUMMARY_RAW_F, generator=g) * 0.1
        summary_raw[0, 0], summary_raw[1, 0] = 1.0, -1.0
        tau = torch.tensor(C.TAUS, dtype=torch.float32)
        y = (10.0 + 4.0 * arm).view(2, 1, 1).repeat(1, C.N_TAU, 1) \
            + 0.02 * tau.view(1, -1, 1)
        y = y.repeat(1, 1, C.N_OUTCOME_TARGETS)
        y[..., 1] += 1.0 + 0.5 * arm
        y[..., 2] += 0.2 * arm
        pair_key = f"J4w{w}@t0=100"
        meta = [
            {"world": "J4", "arm": "wall_v31", "policy": "wall",
             "pair_key": pair_key, "split": "TRAIN"},
            {"world": "J4", "arm": "native", "policy": "native",
             "pair_key": pair_key, "split": "TRAIN"},
        ]
        teacher = torch.zeros(horizon + 1, 2, k, 4)
        teacher[0, :, :, ia.TEACHER_S] = s0
        teacher[0, :, :, ia.TEACHER_LANE] = lane0
        teacher[0, :, :, ia.TEACHER_V] = v0
        teacher[0, :, :, ia.TEACHER_A] = a0
        rollout_accel = true_accel.unsqueeze(0).repeat(horizon, 1, 1)
        rollout_baseline = baseline_idm.unsqueeze(0).repeat(horizon, 2, 1)
        for t in range(1, horizon + 1):
            v_prev = teacher[t - 1, :, :, ia.TEACHER_V]
            v_t = (v_prev + teacher[t - 1, :, :, ia.TEACHER_A]
                   * ia.DT_S).clamp(min=0.0)
            s_t = teacher[t - 1, :, :, ia.TEACHER_S] + 0.5 * (v_prev + v_t) \
                * ia.DT_S
            teacher[t, :, :, ia.TEACHER_S] = s_t
            teacher[t, :, :, ia.TEACHER_V] = v_t
        windows.append({
            "kin": kin, "kin_mask": target_mask, "is_cav": is_cav,
            "baseline_idm": baseline_idm.unsqueeze(0).repeat(2, 1),
            "target_accel": target_accel, "target_mask": target_mask,
            "lane_target": lane_target, "counter": counter,
            "arrivals": arrivals, "summary_raw": summary_raw,
            "global_token": torch.zeros(2, CORR_D_MODEL),
            "outcome_quantiles": y,
            "outcome_mask": torch.ones(2, C.N_TAU, dtype=torch.bool),
            "meta": meta, "teacher": teacher, "rollout_accel": rollout_accel,
            "rollout_baseline_idm": rollout_baseline,
            "rollout_mask": torch.ones(horizon, 2, k, dtype=torch.bool),
            "s0": s0, "v0": v0, "a0": a0, "lane0": lane0, "length0": length0,
            "present0": torch.ones(2, k, dtype=torch.bool),
            "wall_group": -torch.ones(2, k, dtype=torch.long),
            "slot_id": torch.arange(k).unsqueeze(0).repeat(2, 1),
        })
    return windows


__all__ = ["G4Hdv", "G4Arrival", "G4Corr", "seeded_bundle", "make_windows"]
