"""HOLDOUT eligibility guard for final/confirmatory evaluations.

Every final or confirmatory HOLDOUT evaluator MUST call
`load_holdout_exclusions()` and `assert_final_holdout_eligible(worlds)` (or
`filter_final_holdout(worlds)`) before reading any HOLDOUT outcome. The
authoritative list is protocols/holdout_exclusions.json, per owner rulings.

- `excluded`: roots whose outcomes were exposed. REFUSED in final HOLDOUT
  evaluations (owner ruling 2026-09-29 ~19:45, PL-02a).
- `kept_disclosed`: roots exposed at format level only, KEPT in HOLDOUT. Every
  final HOLDOUT report must list them (owner ruling 2026-09-29, WM-70).
"""
from __future__ import annotations

import json
import os
from pathlib import Path

ROOT = Path(os.environ.get("RESEARCH_DENSE_ROOT", "E:/research-dense"))
EXCLUSIONS_PATH = ROOT / "protocols" / "holdout_exclusions.json"


class HoldoutExclusionError(ValueError):
    """A final-HOLDOUT evaluation tried to use an excluded root."""


# --- RC-10: the chunk-5 sealed WM-N1 TEST set -------------------------------
# The chunk-5 worlds (protocols/chunk5_test_seal.json, generated by
# campaign_stage1_v3.plan_chunk5) are a SEALED prospective TEST set: every
# reader EXCEPT the single registered WM-N1 final evaluation refuses them.
CHUNK5_SEAL_FILENAME = "chunk5_test_seal.json"
CHUNK5_SEAL_SCHEMA = "chunk5_test_seal/1"
CHUNK5_ALLOWED_READER = "WM-N1_FINAL_TEST"
#: explicit seal-location override (WM review RC10 objection O5): the seal
#: lives only in the rc10 workspace's protocols/ dir, NOT in every ROOT -
#: set CHUNK5_SEAL_PATH to the seal json (or RESEARCH_DENSE_ROOT to a root
#: that contains protocols/chunk5_test_seal.json).  A MISSING seal file is
#: a loud fail-closed HoldoutExclusionError, never a silent pass.
CHUNK5_SEAL_ENV = "CHUNK5_SEAL_PATH"


def chunk5_seal_path(root=None) -> Path:
    """Resolve the seal json: explicit ``root`` argument first, then the
    ``CHUNK5_SEAL_PATH`` env override, then ``<ROOT>/protocols/`` (ROOT =
    RESEARCH_DENSE_ROOT or its default)."""
    if root is not None:
        return Path(root) / "protocols" / CHUNK5_SEAL_FILENAME
    override = os.environ.get(CHUNK5_SEAL_ENV, "").strip()
    if override:
        return Path(override)
    base = os.environ.get("RESEARCH_DENSE_ROOT", "").strip() or str(ROOT)
    return Path(base) / "protocols" / CHUNK5_SEAL_FILENAME


def load_chunk5_seal(path: Path | None = None) -> dict:
    seal_path = Path(path) if path is not None else chunk5_seal_path()
    if not seal_path.is_file():
        # fail CLOSED and LOUD (O5): a missing seal must never be read as
        # "nothing is sealed"
        raise HoldoutExclusionError(
            f"chunk-5 seal file missing: {seal_path}; refusing (fail-closed) "
            f"- point {CHUNK5_SEAL_ENV} or RESEARCH_DENSE_ROOT at the "
            "workspace holding protocols/chunk5_test_seal.json, or pass "
            "the seal path explicitly")
    data = json.loads(seal_path.read_text(encoding="utf-8"))
    if data.get("schema") != CHUNK5_SEAL_SCHEMA:
        raise HoldoutExclusionError(
            f"unexpected chunk-5 seal schema {data.get('schema')!r}")
    return data


def chunk5_sealed_roots(data: dict | None = None) -> set:
    data = data or load_chunk5_seal()
    return {row for row in data["sealed_roots"]}


def chunk5_reader_allowed(reader: str, data: dict | None = None) -> bool:
    allowed = (data or load_chunk5_seal()).get("allowed_reader")
    return reader == allowed


def assert_chunk5_not_sealed(worlds, *, reader: str,
                             data: dict | None = None,
                             path: Path | None = None) -> None:
    """Refuse any chunk-5 sealed world for a reader that is not the WM-N1
    final test.  A reader that does not touch a sealed root passes."""
    data = data or load_chunk5_seal(path)
    sealed = chunk5_sealed_roots(data)
    bad = sorted({_world_of(w) for w in worlds} & sealed)
    if not bad:
        return
    if chunk5_reader_allowed(reader, data):
        return
    raise HoldoutExclusionError(
        f"chunk-5 sealed TEST roots {bad} may be read ONLY by the "
        f"{data.get('allowed_reader')!r} reader; reader {reader!r} refuses "
        "(protocols/chunk5_test_seal.json; RC-10)")


def filter_chunk5_sealed(worlds, *, reader: str,
                         data: dict | None = None,
                         path: Path | None = None) -> list:
    """Drop the sealed chunk-5 roots a reader may not read."""
    data = data or load_chunk5_seal(path)
    if chunk5_reader_allowed(reader, data):
        return list(worlds)
    sealed = chunk5_sealed_roots(data)
    return [w for w in worlds if _world_of(w) not in sealed]


def load_holdout_exclusions(path: Path | None = None) -> dict:
    data = json.loads(Path(path or EXCLUSIONS_PATH).read_text(encoding="utf-8"))
    if data.get("schema") != "holdout_exclusions/1":
        raise HoldoutExclusionError(f"unexpected schema {data.get('schema')!r}")
    return data


def excluded_roots(data: dict | None = None) -> set:
    data = data or load_holdout_exclusions()
    return {row["world"] for row in data["excluded"]}


def disclosed_roots(data: dict | None = None) -> list:
    data = data or load_holdout_exclusions()
    return list(data["kept_disclosed"])


def _world_of(name: str) -> str:
    # accept a world id or a run name "<world>__<arm>"
    return str(name).split("__", 1)[0]


def assert_final_holdout_eligible(worlds, data: dict | None = None) -> None:
    bad = sorted({_world_of(w) for w in worlds} & excluded_roots(data))
    if bad:
        raise HoldoutExclusionError(
            f"final HOLDOUT evaluation refuses excluded roots {bad} "
            "(protocols/holdout_exclusions.json; owner ruling)")


def filter_final_holdout(worlds, data: dict | None = None) -> list:
    ex = excluded_roots(data)
    return [w for w in worlds if _world_of(w) not in ex]
