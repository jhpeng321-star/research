def walls(ctx):
    """Nested mainline walls (coop_probe slate geometry): the k = 3..6 mainline CAVs nearest behind the ramp
    head (lanes 0/1, within 300 m), all easing -1 m/s^2 for 30 s on the seed-1 policy reference."""
    from tools.mining import probe
    rows = ctx['rows']
    cav = {r['vid']: r for r in rows if r['is_cav'] and r['vid'] in ctx['policy_profile']}
    ramp_q = sorted([r for r in cav.values() if r['lane'] == 2 and -100 <= r['s_m'] <= 75.44],
                    key=lambda r: -r['s_m'])
    head = ramp_q[0]['s_m'] if ramp_q else 75.44
    mains = sorted([r for r in cav.values() if r['lane'] in (0, 1) and r['s_m'] < head+5
                    and head-r['s_m'] <= 300], key=lambda r: -r['s_m'])
    out = []
    for k in WALL_K:
        if len(mains) >= k:
            p = probe.ease_plan(ctx, 'wall', tuple(r['vid'] for r in mains[:k]), 0, HOLD, DEPTH, tag='hw')
            if p is not None:
                out.append(p)
    return out


def seed_snapshot(snap, sid, r):
    from tools.coopmwm import replay_bank as rb
    from tools.coopmwm.protocol import digest
    if r == 1:
        return snap, None
    salt = f'hicavprobe#{sid}#r{r}'
    for n in range(100):
        s = salt if not n else f'{salt}#x{n}'
        g = int(digest(dict(replication=s))[:15], 16)
        if not any(lo <= g <= hi for lo, hi in EVAL):
            return rb.replicate(snap, s), s
    raise ValueError('salt')


def run_verify(ctx_dir, cands, r, tag, kind):
    from tools.coopmwm import sumo_verify as sv
    ctx, snap = load_ctx(ctx_dir)
    snap_r, salt = seed_snapshot(snap, ctx['state_id'], r)
    work = ROOT/'verify'/tag/f'r{r}'
    runner = sv.SubprocessBranchRunner(work/'branches', workers=len(cands)+1, timeout_s=5400)

    def chg(vid, specs):
        charge(f'{tag}_r{r}_{vid}', sum(int(s['sim_s']) for s in specs), kind, len(specs))
    rec = sv.verify(snap_r, cands, runner, chg, 'wm', workers=len(cands)+1, root=work, tail_s=TAIL)
    _write(work/'RECEIPT_COPY.json', {k: rec.get(k) for k in ('verification_id', 'status', 'reason', 'window',
                                                               'J_policy_veh_s', 'charged_sim_s', 'actual_sim_s')})
    return ctx, rec, work, salt


class Tapes:
    def __init__(self, rec, work):
        self.rec, self.bdir, self.cache = rec, work/'branches', {}
        self.idx = {b['branch']: i for i, b in enumerate(rec['branches'])}

    def J(self, i):
        return self.rec['branches'][i]['J_veh_s']

    def tape(self, i):
        from tools.coopmwm import bank_statistics as bs
        if i not in self.cache:
            self.cache[i] = bs._read_result(self.bdir, self.rec['verification_id'], self.rec['branches'][i])
        return self.cache[i]

    def safety(self, i):
        from tools.coopmwm import replay_bank as rb
        b, p = self.rec['branches'][i], self.rec['branches'][0]
        return {k: float(b['window'][k])-float(p['window'][k]) for k in rb.SAFETY_KEYS}

    def abs_safety(self, i):
        from tools.coopmwm import replay_bank as rb
        return {k: float(self.rec['branches'][i]['window'][k]) for k in rb.SAFETY_KEYS}


def lb(ref_tape, alt_tape, window):
    from tools.coopmwm import bank_statistics as bs
    st = bs._stats([(ref_tape, alt_tape, window)])
    return st['lower95_one_sided_veh_s'], {k: st[k] for k in st if not isinstance(st[k], list)}


