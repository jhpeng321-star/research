def stage_b(ctx_dir):
    """Solos for every wall that beat policy on seed 1 (adv LB95 > 0); synergy vs the stage-A group tape."""
    from tools.mining import probe
    ctx = json.loads((Path(ctx_dir)/'CONTEXT.json').read_text())
    sid = ctx['state_id']
    rows = [r for r in a_rows(sid) if 'group_id' in r]
    beat = [r for r in rows if (r.get('adv_lb95') or -1) > 0 and (r.get('group_adv') or 0) >= MATERIAL_VEH_S]
    if not beat:
        _append(ROOT/'results'/'B_skipped.jsonl', dict(state_id=sid, reason='no wall with adv LB95 > 0 and '
                                                       f'group_adv >= {MATERIAL_VEH_S} veh-s', unix=time.time()))
        return []
    plans = {p['id']: p for p in walls(ctx)}
    solos, owner = [], {}
    for r in beat:
        for s in probe.solos(plans[r['group_id']]):
            if s['id'] not in {c['id'] for c in solos}:
                solos.append(s)
            owner.setdefault(r['group_id'], []).append(s['id'])
    ctx, rec, work, _ = run_verify(ctx_dir, solos, 1, f'B_{sid}', 'screenB')
    base = dict(stage='B', state_id=sid, world=ctx['world'], t0=ctx['t0'], seed_index=1, host=HOST,
                verification_id=rec['verification_id'], status=rec['status'], work=str(work))
    if rec['status'] not in ('accepted', 'rejected'):
        _append(ROOT/'results'/'B.jsonl', dict(base, error=rec.get('reason')))
        return []
    a0 = beat[0]
    from tools.coopmwm import sumo_verify as sv
    import types
    ra = json.loads(next((Path(a0['work'])/'verifications').glob('*.json')).read_text())
    TA, TB = Tapes(ra, Path(a0['work'])), Tapes(rec, work)
    same_policy = TA.J(0) == TB.J(0) and ra['window'] == rec['window']
    sidx = {c['id']: i for i, c in enumerate(solos, 1)}
    out = []
    for r in beat:
        sj = {s: TB.J(sidx[s]) for s in owner[r['group_id']]}
        row = dict(base, group_id=r['group_id'], members=r['members'], n_members=r['n_members'],
                   J_policy=TA.J(0), J_policy_B=TB.J(0), policy_reproduced=same_policy, J_group=r['J_group'],
                   group_adv=r['group_adv'], adv_lb95=r['adv_lb95'], J_solos=sj,
                   solo_safety={s: TB.safety(sidx[s]) for s in sj if TB.J(sidx[s]) is not None})
        if any(v is None for v in sj.values()) or not same_policy:
            row['synergy_status'] = 'incomplete' if same_policy else 'policy_not_reproduced'
        else:
            best = min(sj, key=lambda k: (sj[k], k))
            row.update(best_solo=best, best_solo_adv=TA.J(0)-sj[best], synergy=sj[best]-r['J_group'])
            try:
                row['synergy_lb95'], row['synergy_stats'] = lb(TB.tape(sidx[best]), TA.tape(r['branch_index']),
                                                              ra['window'])
                row['synergy_status'] = 'admitted' if (row['synergy_lb95'] > 0 and r['adv_lb95'] > 0) \
                    else 'not_admitted'
            except Exception as e:
                row['synergy_status'] = 'data_missing'
                row['error'] = repr(e)
        out.append(row)
        _append(ROOT/'results'/'B.jsonl', row)
    return out


