    ctx, rec, work, _ = run_verify(ctx_dir, ws, 1, f'A_{sid}', 'screenA')
    base.update(verification_id=rec['verification_id'], status=rec['status'], window=rec.get('window'),
                J_policy=rec.get('J_policy_veh_s'), work=str(work))
    if rec['status'] not in ('accepted', 'rejected'):
        _append(ROOT/'results'/'A.jsonl', dict(base, error=rec.get('reason')))
