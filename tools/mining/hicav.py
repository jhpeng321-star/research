def slots_needed(ctx, members, range_m=100.0):
    """min over members m of the V2V slot count (ego + nearest other CAVs by |ds| within range, ties by vid)
    needed for m to see every other wall member at t0; None if no member sees all within range."""
    cav = {r['vid']: r for r in ctx['rows'] if r['is_cav']}
    best = None
    for m in members:
        me = cav[m]
        others = sorted([r for r in cav.values() if r['vid'] != m and abs(r['s_m']-me['s_m']) <= range_m],
                        key=lambda r: (abs(r['s_m']-me['s_m']), r['vid']))
        order = [r['vid'] for r in others]
        if not all(x in order for x in members if x != m):
            continue
        need = 1+max([order.index(x)+1 for x in members if x != m] or [0])
        best = need if best is None else min(best, need)
    return best


# ------------------------------------------------------------------ driver

def _launch(args, tag, env=None):
    log = open(ROOT/'logs'/f'{tag}.log', 'w')
    pr = subprocess.Popen(['nice', '-n', '19', sys.executable, '-B', '-u', '-m', 'tools.mining.hicav']+args,
                          stdout=log, stderr=subprocess.STDOUT, stdin=subprocess.DEVNULL, start_new_session=True,
                          cwd=str(ROOT), env=env or dict(os.environ))
    _append(ROOT/'PIDS.jsonl', dict(tag=tag, pid=pr.pid, args=args, unix=time.time(), host=HOST))
    return pr


def drive(plan_path):
    """Slot-bounded scheduler (<= SLOTS concurrent SUMO processes). plan: {collect: [seeds], native: [seeds],
    reserve_confirm: sim-s kept for stage C, slots: N, max_rank: screen contexts with score rank <= this}."""
    plan = json.loads(Path(plan_path).read_text())
    slots, reserve = int(plan['slots']), int(plan.get('reserve_confirm', 0))
    max_rank = int(plan.get('max_rank', 1))
    (ROOT/'logs').mkdir(exist_ok=True)
    queue = [dict(kind='collect', args=['collect', str(s)], slots=1, tag=f'collect_{s}', prio=3)
             for s in plan['collect']]
    queue += [dict(kind='native', args=['native', str(s)], slots=1, tag=f'native_{s}', prio=4)
              for s in plan['native']]
    running, done, seen = [], [], set()
    state = ROOT/'DRIVER_STATE.json'
    deferred = []

    def est(item):
        return item.get('est', 1200*item['slots'])

    adopt = [coll_id(x) for x in plan.get('adopt_collect', [])]

    def queue_contexts(cid):
        rec = ROOT/'collect'/cid/'COLLECTION_RECEIPT.json'
        if not rec.exists():
            return
        for c in json.loads(rec.read_text())['contexts']:
            ctx = json.loads((Path(c['dir'])/'CONTEXT.json').read_text())
            nw = len(walls(ctx))
            if not nw:
                continue
            item = dict(kind='A', args=['A', c['dir']], slots=nw+1, tag=f'A_{ctx["state_id"]}', prio=2,
                        rank=c['rank'], est=(nw+1)*(c['t0']+HOLD+TAIL), dir=c['dir'])
            (queue if c['rank'] <= max_rank else deferred).append(item)

    while queue or running or deferred or adopt:
        if (ROOT/'STOP').exists():
            break
        for cid in list(adopt):
            if (ROOT/'collect'/cid/'COLLECTION_RECEIPT.json').exists():
                adopt.remove(cid)
                queue_contexts(cid)
        for item in list(running):
            if item['proc'].poll() is not None:
                running.remove(item)
                item['rc'] = item['proc'].returncode
                done.append({k: v for k, v in item.items() if k != 'proc'})
                # successors
                if item['kind'] == 'collect':
                    queue_contexts(item['coll_id'])
                elif item['kind'] == 'A':
                    ctx = json.loads((Path(item['dir'])/'CONTEXT.json').read_text())
                    beat = [r for r in a_rows(ctx['state_id']) if (r.get('adv_lb95') or -1) > 0]
                    if beat:
                        mem = {m for r in beat for m in r['members']}
                        queue.append(dict(kind='B', args=['B', item['dir']], slots=len(mem)+1,
                                          tag=f'B_{ctx["state_id"]}', prio=1,
                                          est=(len(mem)+1)*(ctx['t0']+HOLD+TAIL), dir=item['dir']))
                elif item['kind'] == 'B':
                    ctx = json.loads((Path(item['dir'])/'CONTEXT.json').read_text())
                    p = ROOT/'results'/'B.jsonl'
                    rows = [r for r in (json.loads(x) for x in p.read_text().splitlines() if x.strip())
                            if r['state_id'] == ctx['state_id']] if p.exists() else []
                    adm = sorted([r for r in rows if r.get('synergy_status') == 'admitted'],
                                 key=lambda r: -r['synergy_lb95'])
                    for r in adm[:int(plan.get('confirm_per_ctx', 1))]:
                        for s in plan.get('confirm_seeds', [2, 3]):
                            queue.append(dict(kind='C', args=['C', item['dir'], r['group_id'], str(s)],
                                              slots=r['n_members']+2, tag=f'C_{ctx["state_id"]}_k{r["n_members"]}_r{s}',
                                              prio=0, est=(r['n_members']+2)*(ctx['t0']+HOLD+TAIL), dir=item['dir']))
        # budget-aware deferred contexts: screen extra ranks only if budget remains
        if not queue and not running and not adopt and deferred:
            if time.time() > float(plan.get('deadline_deferred', 1e18)):
                break
            left = CAP-spent()-reserve
            deferred.sort(key=lambda x: (x['rank'], x['tag']))
            take = []
            for d in deferred:
                if est(d) <= left:
                    take.append(d)
                    left -= est(d)
            deferred = []
            queue += take
            if not take:
                break
        used = sum(i['slots'] for i in running)+len(adopt)
        queue.sort(key=lambda x: (x['prio'], x.get('rank', 0), x['tag']))
        now = time.time()
        committed = sum(est(i) for i in running if now-i['start'] < 120)   # launched, not yet charged
        for item in list(queue):
            if item['kind'] in ('A', 'B') and now > float(plan.get('deadline_ab', 1e18)):
                queue.remove(item)
                done.append(dict(item, skipped='deadline'))
                continue
            if item['kind'] == 'C' and now > float(plan.get('deadline_c', 1e18)):
                queue.remove(item)
                done.append(dict(item, skipped='deadline'))
                continue
            if item['tag'] in seen:
                queue.remove(item)
                continue
            if used+item['slots'] > slots:
                continue
            limit = CAP-(0 if item['kind'] == 'C' else reserve)
            if spent()+committed+est(item) > limit+(1200 if item['kind'] in ('collect', 'native') else 0):
                if item['kind'] in ('A', 'B'):
                    queue.remove(item)
                    done.append(dict({k: v for k, v in item.items()}, skipped='budget'))
                continue
            queue.remove(item)
            seen.add(item['tag'])
            if item['kind'] == 'collect':
                item['coll_id'] = coll_id(item['args'][1])
            item['proc'] = _launch(item['args'], item['tag'])
            item['start'] = time.time()
            running.append(item)
            used += item['slots']
            committed += est(item)
        _write(state, dict(unix=time.time(), host=HOST, spent=spent(), cap=CAP, used_slots=used,
                           running=[{k: v for k, v in i.items() if k != 'proc'} for i in running],
                           queue=queue, deferred=deferred, done=done))
        time.sleep(10)
    _write(state, dict(unix=time.time(), host=HOST, spent=spent(), cap=CAP, finished=True, done=done,
                       queue=queue, deferred=deferred))


def main(argv):
    cmd = argv[0]
    (ROOT/'results').mkdir(parents=True, exist_ok=True)
    try:
        if cmd == 'collect':
            print(json.dumps(dict(saved=collect(int(argv[1])))), flush=True)
        elif cmd == 'native':
            print(json.dumps(native(int(argv[1]))), flush=True)
        elif cmd == 'A':
            print(json.dumps(dict(n=len(stage_a(argv[1])))), flush=True)
        elif cmd == 'B':
            print(json.dumps(dict(n=len(stage_b(argv[1])))), flush=True)
        elif cmd == 'C':
            print(json.dumps(dict(row=stage_c(argv[1], argv[2], int(argv[3])) is not None)), flush=True)
        elif cmd == 'drive':
            drive(argv[1])
        elif cmd == 'spent':
            print(spent())
    except Exception as e:
        import traceback
        print(json.dumps(dict(cmd=argv, error=repr(e), tb=traceback.format_exc()[-3000:])), flush=True)
        raise


if __name__ == '__main__':
    main(sys.argv[1:])
